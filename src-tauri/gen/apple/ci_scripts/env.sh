#!/bin/bash
# Shared helpers for Xcode Cloud ci_scripts. Sourced, not executed.

NUVO_XCODE_CLOUD_REQUIRED_VARS=(
  VITE_SUPABASE_URL
  VITE_SUPABASE_ANON_KEY
  VITE_POSTHOG_PROJECT_TOKEN
  VITE_POSTHOG_HOST
  VITE_NUVO_IAP_MONTHLY
  VITE_NUVO_IAP_ANNUAL
  APPLE_DEVELOPMENT_TEAM
)

nuvo_require_xcode_cloud_env() {
  local missing=()
  local var
  for var in "${NUVO_XCODE_CLOUD_REQUIRED_VARS[@]}"; do
    if [ -z "${!var:-}" ]; then
      missing+=("$var")
    fi
  done
  if [ "${#missing[@]}" -ne 0 ]; then
    echo "error: missing required Xcode Cloud environment variables:" >&2
    for var in "${missing[@]}"; do
      echo "  - $var" >&2
    done
    echo "Set them on the Xcode Cloud workflow. Do not put CFBundleVersion here." >&2
    return 1
  fi
}

# Write a file the "Build Rust Code" phase can source after Cloud hides PATH.
nuvo_write_xcode_cloud_env() {
  local dest_home="${HOME}/.nuvo_xcode_cloud_env.sh"
  local dest_tmp="/tmp/nuvo_xcode_cloud_env.sh"
  local node20=""
  if command -v brew >/dev/null 2>&1 && brew --prefix node@20 >/dev/null 2>&1; then
    node20="$(brew --prefix node@20)/bin"
  fi

  {
    echo "# Generated by Nuvo Xcode Cloud ci_scripts — do not edit."
    echo "export PATH=\"${HOME}/.cargo/bin:${node20}:/usr/local/bin:/opt/homebrew/bin:\$PATH\""
    echo "[ -f \"${HOME}/.cargo/env\" ] && . \"${HOME}/.cargo/env\""
    local var
    for var in "${NUVO_XCODE_CLOUD_REQUIRED_VARS[@]}"; do
      if [ -n "${!var:-}" ]; then
        printf 'export %s=%q\n' "$var" "${!var}"
      fi
    done
    # Watch stays off on Cloud unless the workflow set it.
    printf 'export NUVO_IOS_WATCH=%q\n' "${NUVO_IOS_WATCH:-0}"
  } | tee "$dest_home" > "$dest_tmp"
  chmod 600 "$dest_home" "$dest_tmp"

  # Subsequent login shells (and some script phases) pick this up.
  local profile
  for profile in "${HOME}/.zshenv" "${HOME}/.zprofile" "${HOME}/.bashrc" "${HOME}/.bash_profile"; do
    if [ -f "$profile" ] && grep -q "nuvo_xcode_cloud_env.sh" "$profile"; then
      continue
    fi
    echo "[ -f \"${HOME}/.nuvo_xcode_cloud_env.sh\" ] && . \"${HOME}/.nuvo_xcode_cloud_env.sh\"" >> "$profile"
  done

  echo "Wrote Xcode Cloud env → $dest_home"
}
