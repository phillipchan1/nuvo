-- Neon schema: what production's `public` schema IS (D-241).
--
-- Production was not made by this file. The cutover copied Supabase's tables
-- (scripts/cutover_copy.py), so for months this file described a thinner,
-- differently-keyed database than the one the Worker writes to — and a
-- migration or a Worker write that passed against it could fail in prod
-- (2026-11-17: `recurrences.rrule` and `event_domain_routing.id` existed only
-- here). So the tables below are GENERATED from a pg_dump of production:
--
--   node scripts/schema-drift.mjs               # diffs this file against prod; run before ANY migration
--   node scripts/schema-drift.mjs --emit-tables # prints prod's tables in this file's form
--
-- See docs/schema-drift.md. A schema change is written here first (idempotent,
-- `IF NOT EXISTS`), tested on the pg_dump copy (`--migration`), applied to prod
-- by hand, and the drift check must be clean afterwards.
--
-- Owner is public.users(id). Isolation is owner-scoped SQL in the Worker
-- (`user_id = session`), not Postgres RLS: the Worker uses a privileged
-- connection and scopes every query by user_id; generic /api/data does not
-- expose the token tables. Refresh tokens / PATs / app passwords / ICS URLs
-- live in refresh_token_enc + refresh_token_iv + key_version (AES-GCM); the
-- *_secret_id columns stay nullable for cutover traceability and are never
-- read on Neon. prove-isolation-mutation deletes the owner clauses.
--
-- Not a replay of supabase/migrations (those assume auth.users, vault,
-- realtime, pg_cron). better-auth.sql and field-ts.sql are applied after this.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------
-- Production's tables — generated by `scripts/schema-drift.mjs --emit-tables`
-- from a pg_dump of Neon `main` (2026-11-17). Better Auth, billing and the
-- change feed are hand-written below / in better-auth.sql.
--
-- Shapes that differ from what you might expect, and have bitten:
--   • recurrences has no `rrule`: the rule is kind · freq · interval · byweekday
--     · bymonthday · bysetpos · bymonth · anchor_date · until_date · max_count,
--     written exactly as the SPA's useRecurrence writes it.
--   • event_domain_routing has no `id`: it is keyed (user_id, event_key).
--     `domain_id` is the model's answer, `manual_domain_id` the person's.
--   • reminders.id has no default — the writer supplies it.
--   • tasks.status / tasks.priority / recurrences.priority are enums.
--   • external_events.recurring_event_id is GENERATED from raw->>'recurringEventId':
--     never write it (writing it stopped Google sync in prod, 2026-11-13..17).
-- ---------------------------------------------------------------------------

DO $$ BEGIN
  IF to_regtype('public.calendar_provider') IS NULL THEN
    CREATE TYPE public.calendar_provider AS ENUM ('google', 'm365', 'ics', 'icloud');
  END IF;
END $$;

DO $$ BEGIN
  IF to_regtype('public.sync_direction') IS NULL THEN
    CREATE TYPE public.sync_direction AS ENUM ('two_way', 'read_only');
  END IF;
END $$;

DO $$ BEGIN
  IF to_regtype('public.task_priority') IS NULL THEN
    CREATE TYPE public.task_priority AS ENUM ('none', 'low', 'medium', 'high');
  END IF;
END $$;

DO $$ BEGIN
  IF to_regtype('public.task_status') IS NULL THEN
    CREATE TYPE public.task_status AS ENUM ('inbox', 'planned', 'done', 'trashed', 'backlog');
  END IF;
END $$;

